for (const [lang, filename] of Object.entries(langMap)) {
  const filePath = path.join(localesDir, filename);
  let content = fs.readFileSync(filePath, 'utf8');

  const linesToAdd = [];
  for (const [key, map] of Object.entries(newKeys)) {
    if (!content.includes(`'${key}':`)) {
      const val = (map[lang] || map['en']).replace(/'/g, "\\'");
      linesToAdd.push(`  '${key}': '${val}',`);
    }
  }

  if (linesToAdd.length === 0) {
    console.log(`Skipping ${filename} (already up to date)`);
    continue;
  }

  const insertIndex = content.lastIndexOf('} as const;');
  if (insertIndex !== -1) {
    const newContent = content.slice(0, insertIndex) + linesToAdd.join('\n') + '\n' + content.slice(insertIndex);
    fs.writeFileSync(filePath, newContent, 'utf8');
    console.log(`Updated ${filename}`);
  } else {
    const altIndex = content.lastIndexOf('};');
    if (altIndex !== -1) {
      const newContent = content.slice(0, altIndex) + linesToAdd.join('\n') + '\n' + content.slice(altIndex);
      fs.writeFileSync(filePath, newContent, 'utf8');
      console.log(`Updated ${filename} (alt)`);
    } else {
      console.error(`Could not find closing bracket in ${filename}`);
    }
  }
}
